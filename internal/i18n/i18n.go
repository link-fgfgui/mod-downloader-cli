var (
	activeMu     sync.RWMutex
	activeLocale = Resolve(LanguageSystem, nil)
)

// Normalize maps an arbitrary preference value to "zh" | "en" | "system".
// Port of normalizeLanguagePreference: trims+lowercases; "zh","zh-cn","zh-hans"
// -> "zh"; "en" -> "en"; anything else -> "system".
func Normalize(value string) string {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case LanguageChinese, "zh-cn", "zh-hans":
		return LanguageChinese
	case LanguageEnglish:
		return LanguageEnglish
	default:
		return LanguageSystem
	}
}

// Resolve resolves a preference + system locales to a concrete locale
// ("zh" | "en"). Port of resolveLanguagePreference: if Normalize != "system"
// return it; else use the first non-empty system locale and return "zh" if it
// lowercases to a prefix "zh", otherwise "en".
func Resolve(preference string, systemLocales []string) string {
	normalized := Normalize(preference)
	if normalized != LanguageSystem {
		return normalized
	}
	primary := ""
	for _, locale := range systemLocales {
		if strings.TrimSpace(locale) != "" {
			primary = locale
			break
		}
	}
	if strings.HasPrefix(strings.ToLower(strings.TrimSpace(primary)), "zh") {
		return LanguageChinese
	}
	return LanguageEnglish
}

// SystemLocales reads the process locale preferences in priority order. It is
// used when the persisted language preference is "system".
func SystemLocales() []string {
	var locales []string
	for _, key := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		if value := strings.TrimSpace(os.Getenv(key)); value != "" {
			locales = append(locales, value)
		}
	}
	if language := strings.TrimSpace(os.Getenv("LANGUAGE")); language != "" {
		for _, value := range strings.Split(language, ":") {
			if value = strings.TrimSpace(value); value != "" {
				locales = append(locales, value)
			}
		}
	}
	return locales
}

// Apply sets the active process-wide locale and returns it ("zh"|"en").
func Apply(preference string) string {
	locale := Resolve(preference, SystemLocales())
	activeMu.Lock()
	activeLocale = locale
	activeMu.Unlock()
	return locale
}

// Current returns the active locale ("zh"|"en").
func Current() string {
	activeMu.RLock()
	defer activeMu.RUnlock()
	return activeLocale
}

// Lookup returns the raw message for an explicit lang ("zh"|"en") and dotted key.
func Lookup(lang, key string) (string, bool) {
	messages := enMessages
	if lang == LanguageChinese {
		messages = zhMessages
	}
	value, ok := messages[key]
	return value, ok
}

// T translates key for the current locale using params interpolation. It
// mirrors vue-i18n with fallbackLocale "en": the active locale is tried first,
// then "en", and finally the key itself is returned.
func T(key string, params ...map[string]string) string {
	message, ok := Lookup(Current(), key)
	if !ok {
		message, ok = Lookup(LanguageEnglish, key)
	}
	if !ok {
		message = key
	}
	merged := make(map[string]string)
	for _, p := range params {
		for k, v := range p {
			merged[k] = v
		}
	}
	for name, value := range merged {
		message = strings.ReplaceAll(message, "{"+name+"}", value)
	}
	return message
}
