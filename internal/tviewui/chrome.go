// uiText returns the localized chrome label for key.
func uiText(key string) string {
	entry, ok := chromeLabels[key]
	if !ok {
		return key
	}
	if i18n.Current() == i18n.LanguageChinese {
		return entry[0]
	}
	return entry[1]
}
